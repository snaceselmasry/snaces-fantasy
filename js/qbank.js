/* ---------- حالة التحديات اليومية والأسبوعية (مشتركة بين الصفحات) ---------- */
function qbTodayKey(d) {
  const t = d ? new Date(d) : new Date();
  return t.toLocaleDateString('en-CA');
}
function qbWeekInfo(d) {
  const t = d ? new Date(d) : new Date();
  const x = new Date(Date.UTC(t.getFullYear(), t.getMonth(), t.getDate()));
  const day = x.getUTCDay() || 7;
  x.setUTCDate(x.getUTCDate() + 4 - day);
  const y = x.getUTCFullYear();
  const w = Math.ceil(((x - new Date(Date.UTC(y, 0, 1))) / 86400000 + 1) / 7);
  /* نهاية الأسبوع: الأحد 23:59:59 بالتوقيت المحلي */
  const end = new Date(t.getFullYear(), t.getMonth(), t.getDate());
  end.setDate(end.getDate() + ((7 - (end.getDay() || 7)) % 7));
  end.setHours(23, 59, 59, 999);
  return { key: y + '-W' + String(w).padStart(2, '0'), end: end.getTime() };
}
function qbTimeLeft(until) {
  let s = Math.max(0, Math.floor((until - Date.now()) / 1000));
  const d = Math.floor(s / 86400); s %= 86400;
  const h = Math.floor(s / 3600); s %= 3600;
  const m = Math.floor(s / 60); s %= 60;
  if (d > 0) return d + ' يوم و' + h + ' ساعة';
  if (h > 0) return h + ' ساعة و' + m + ' دقيقة';
  return m + ':' + String(s).padStart(2, '0');
}
function qbChallengeState() {
  const today = qbTodayKey();
  let day = null, week = null;
  try { day = typeof ACC !== 'undefined' ? ACC.get('snaces_day', null) : null; } catch (e) { }
  try { week = typeof ACC !== 'undefined' ? ACC.get('snaces_week', null) : null; } catch (e) { }
  if (!day || day.date !== today || day.v !== 3) day = { date: today, v: 3, i: 0, score: 0, done: false };
  const wi = qbWeekInfo();
  if (!week || week.week !== wi.key) week = { week: wi.key, i: 0, score: 0, done: false };
  const midnight = new Date(); midnight.setHours(24, 0, 0, 0);
  return {
    daily: { state: day, label: day.done ? 'مكتمل' : day.i > 0 ? 'بدأ' : 'متاح', left: midnight.getTime() },
    weekly: { state: week, label: week.done ? 'مكتمل' : week.i > 0 ? 'بدأ' : 'متاح', left: wi.end, key: wi.key }
  };
}

