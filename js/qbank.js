/* ---------- سجل الظهور ومنع التكرار ---------- */
const QBHistory = (() => {
  const read = () => {
    let h = null;
    try { h = typeof ACC !== 'undefined' ? ACC.get(QH_KEY, null) : store.get(QH_KEY, null); } catch (e) { h = null; }
    return h && typeof h === 'object' ? h : {};
  };
  const write = h => {
    const keys = Object.keys(h);
    if (keys.length > 4000) {
      keys.sort((a, b) => (+h[a] || 0) - (+h[b] || 0));
      keys.slice(0, keys.length - 4000).forEach(k => { delete h[k]; });
    }
    try { typeof ACC !== 'undefined' ? ACC.set(QH_KEY, h) : store.set(QH_KEY, h); } catch (e) { }
  };
  const mark = ids => {
    if (!ids || !ids.length) return;
    const h = read(), now = Date.now();
    ids.forEach(id => { if (id) h[String(id)] = now; });
    write(h);
  };
  const seen = () => read();
  const count = () => Object.keys(read()).length;
  const clear = () => { try { typeof ACC !== 'undefined' ? ACC.set(QH_KEY, {}) : store.set(QH_KEY, {}); } catch (e) { } };
  return { read, mark, seen, count, clear };
})();

/* ---------- اختيار أسئلة بدون تكرار ---------- */
function qbTake(pool, n, idOf, markSeen) {
  const rows = (pool || []).filter(Boolean);
  if (!rows.length || n <= 0) return [];
  const hist = QBHistory.read();
  const withId = rows.map(r => ({ r, id: idOf ? idOf(r) : (r && r[7]) || 'qb:' + qbHash(r && r[2]) }));
  const unseen = [], seen = [];
  withId.forEach(x => { if (x.id && hist[x.id]) seen.push(x); else unseen.push(x); });
  seen.sort((a, b) => (+hist[a.id] || 0) - (+hist[b.id] || 0));
  const ordered = qbShuffle(unseen).concat(seen);
  /* ضمان عدم تكرار نفس المعرف داخل الجولة حتى لو المصدر فيه صفوف مكررة */
  const out = [], used = new Set();
  for (const x of ordered) {
    if (x.id && used.has(x.id)) continue;
    if (x.id) used.add(x.id);
    out.push(x);
    if (out.length >= Math.min(n, ordered.length)) break;
  }
  if (markSeen !== false) QBHistory.mark(out.map(x => x.id));
  return out.map(x => x.r);
}

/* سؤال واحد غير متكرر (للألعاب السريعة) */
function qbPickOne(pool, idOf) {
  const rows = qbTake(pool, 1, idOf);
  return rows[0] || (pool && pool[0]) || null;
}

