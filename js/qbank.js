const QH_KEY = 'snaces_qhist';

const qbNorm = s => String(s == null ? '' : s).replace(/\s+/g, ' ').trim();
const qbKey = s => qbNorm(s).replace(/[أإآ]/g, 'ا').replace(/ى/g, 'ي').replace(/ة/g, 'ه').toLowerCase();
const qbHash = s => {
  let h = 2166136261;
  const t = String(s || '');
  for (let i = 0; i < t.length; i++) { h ^= t.charCodeAt(i); h = Math.imul(h, 16777619); }
  return (h >>> 0).toString(36);
};
const qbSeeded = seed => {
  let a = parseInt(qbHash(seed), 36) || 1;
  return () => {
    a ^= a << 13; a >>>= 0; a ^= a >> 17; a ^= a << 5; a >>>= 0;
    return a / 4294967296;
  };
};
const qbShuffle = arr => {
  const a = arr.slice();
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    const t = a[i]; a[i] = a[j]; a[j] = t;
  }
  return a;
};

